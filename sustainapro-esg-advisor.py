import streamlit as st
import google.generativeai as genai

# Configuración de la página en Streamlit
st.set_page_config(
    page_title="SustainaPro Aviation Advisor", page_icon="✈️", layout="wide"
)

st.title("✈️ SustainaPro Aviation Sustainability Advisor")
st.markdown(
    "Sistema experto de consultoría preliminar para evaluar la madurez ESG y priorizar iniciativas operativas en operadores aéreos regionales."
)

# Configuración segura de la API key (en Colab para pruebas, luego usa st.secrets para la nube)
# En Streamlit Cloud esto leerá st.secrets["GEMINI_API_KEY"]
api_key = st.secrets.get("GEMINI_API_KEY", "")

if not api_key:
    st.warning(
        "⚠️ Por favor, configura tu GEMINI_API_KEY en los secretos de Streamlit."
    )
else:
    genai.configure(api_key=api_key)
    model = genai.GenerativeModel("gemini-1.5-flash")
    # Sidebar para la entrada de datos del cliente (aerolínea regional)
    st.sidebar.header("📋 Parámetros de la Aerolínea")
    flota = st.sidebar.selectbox(
        "Tipo de Flota Principal",
        [
            "Turbohélice regional (ej. ATR 42/72)",
            "Aviones ligeros de pistón",
            "Jets regionales pequeños",
        ],
    )
    vuelos_diarios = st.sidebar.number_input(
        "Promedio de vuelos diarios", min_value=5, max_value=100, value=25
    )
    enfoque_actual = st.sidebar.selectbox(
        "Principal desafío operativo",
        [
            "Consumo de combustible en rutas",
            "Eficiencia energética en hangares/rampa",
            "Gestión de residuos sólidos y materiales",
        ],
    )

    if st.button("Generar Diagnóstico y Roadmap ESG"):
        # Bloque protegido try/except para cumplir con la rúbrica y evitar errores de API
        try:
            with st.spinner(
                "El Socio Director está analizando el perfil operativo..."
            ):
                # Inicializar el modelo con el rol estratégico de la consultora
                generation_config = {
                    "temperature": 0.3,
                    "max_output_tokens": 1000,
                }
                model = genai.GenerativeModel(
                    model_name="gemini-2.5-flash",
                    generation_config=generation_config,
                    system_instruction=(
                        "Eres el Socio Director de SustainaPro Consulting, "
                        "una firma boutique especializada en sostenibilidad aeroespacial. "
                        "Asesoras a operadores aéreos regionales enfocándote estrictamente "
                        "en eficiencia operativa, optimización de combustible, gestión de rampa "
                        "y reducción de residuos. Descartas tecnologías inviables a corto plazo como el SAF. "
                        "Tu tono es ejecutivo, riguroso, experto y orientado a resultados prácticos."
                    ),
                )

                prompt = (
                    f"Genera un reporte de consultoría preliminar para un operador aéreo regional con las siguientes características:\n"
                    f"- Tipo de flota: {flota}\n"
                    f"- Operación diaria: {vuelos_diarios} vuelos\n"
                    f"- Desafío principal: {enfoque_actual}\n\n"
                    f"El reporte debe incluir estrictamente:\n"
                    f"1. Puntuación estimada de Madurez ESG (sobre 100) y breve análisis.\n"
                    f"2. Priorización de 3 iniciativas operativas de alto impacto (excluyendo SAF).\n"
                    f"3. Un roadmap preliminar en fases.\n"
                    f"4. KPIs recomendados para el seguimiento.\n"
                    f"5. Un resumen ejecutivo directo."
                )

                response = model.generate_content(prompt)

                # Mostrar el resultado en pantalla
                st.success("¡Diagnóstico generado con éxito!")
                st.markdown("### 📊 Reporte de Consultoría Preliminar")
                st.write(response.text)

        except Exception as e:
            st.error(
                f"Ocurrió un error al comunicarse con el servicio de IA. Por favor, intente de nuevo más tarde. (Detalle técnico: {e})"
            )

